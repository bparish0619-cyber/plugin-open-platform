import { readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const upstream = await readFile(new URL('third_party/opusscript/opusscript_native_nasm.js', root), 'utf8');
const bindings = await readFile(new URL('third_party/opusscript/csp-bindings.js', root), 'utf8');
const begin = upstream.indexOf('function zb(a,b,c,d,e,f)');
const end = upstream.indexOf('function Ab(', begin);
if (begin < 0 || end < 0) throw new Error('Pinned opusscript binding layout changed');
// Shadow Node globals: this self-contained factory is used as a browser ESM,
// including in Node tests, and must never try to require fs/path or fetch WASM.
const decoder = '// Generated by tools/sync-audio-playback.mjs; opusscript 0.1.1, libopus 1.4.\n' +
  '// See opus-decoder-LICENSE.txt. No WASM or dynamic code generation.\n' +
  'const process = undefined;\n' + upstream.slice(0, begin) + bindings + upstream.slice(end) +
  '\nexport default Module;\n';
const license = await readFile(new URL('third_party/opusscript/LICENSE', root), 'utf8') + '\n' +
  await readFile(new URL('third_party/opusscript/COPYING.libopus', root), 'utf8');
const playback = await readFile(new URL('examples/shared/recording-playback.js', root), 'utf8');
for (const example of ['talking-pet', 'audio-capture-lab']) {
  const vendor = new URL(`examples/${example}/vendor/`, root);
  await writeFile(new URL('opus-decoder.esm.js', vendor), decoder);
  await writeFile(new URL('opus-decoder-LICENSE.txt', vendor), license);
  await writeFile(new URL('recording-playback.js', vendor), playback);
}
